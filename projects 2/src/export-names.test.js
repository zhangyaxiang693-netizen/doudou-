import test from "node:test";
import assert from "node:assert/strict";
import { assignExportNames, makeExportArchiveName } from "./export-names.js";

const pages = [{ id: "p", name: "模板3 抽奖 + 消耗返", nodes: [] }];
function entry(id, schemaId, audienceTitle = "人群1", dimensionTitle = "默认维度", naming = {}) {
  return {
    id, pageId: "p", nodeId: schemaId, moduleTitle: schemaId,
    sourceNode: { id: schemaId, schemaId }, dimensionTitle,
    naming: { audienceTitle, ...naming },
  };
}
const rename = (entries, options = {}) => assignExportNames(entries, { pages, ...options });

test("named audiences replace generic version numbers and keep consumption intervals", () => {
  const [item] = rename([entry("a", "核心玩法模块-抽奖消返-3列", "人群1",
    "个人素人-近30天消耗(0,100]", { stateTitle: "未报名" })]);
  assert.equal(item.fileName, "个人素人-近30天消耗(0,100].png");
  assert.equal(item.filePath, "【落地页】/抽奖消耗返/未报名/个人素人-近30天消耗(0,100].png");
});

test("real version names are used even when the graph dimension is a system label", () => {
  const [item] = rename([entry("a", "头图", "高消耗老客", "蓝图版本")]);
  assert.equal(item.fileName, "高消耗老客.png");
});

test("audience and tier are combined without repeated labels", () => {
  const [item] = rename([entry("a", "头图", "个人素人-近30天消耗(100,500]", "个人素人")]);
  assert.equal(item.fileName, "个人素人-近30天消耗(100,500].png");
});

test("a named audience stays named while only unnamed audiences retain numbers", () => {
  const items = rename([
    entry("a", "头图", "高消耗老客"),
    entry("b", "头图", "人群2"),
  ]);
  assert.deepEqual(items.map((item) => item.fileName), ["高消耗老客.png", "人群2.png"]);
  assert.equal(rename([entry("a", "头图")])[0].fileName, "默认.png");
});

test("explicit platform and state are preserved without generating additional variants", () => {
  const items = rename([entry("a", "核心玩法模块-抽奖-未报名",
    "【安卓】个人素人-近30天消耗0", "", { stateTitle: "报名前" })]);
  assert.equal(items.length, 1);
  assert.equal(items[0].fileName, "【安卓】个人素人-近30天消耗0.png");
  assert.equal(items[0].filePath, "【落地页】/九宫格/未报名/【安卓】个人素人-近30天消耗0.png");
});

test("task states use completion names and keep their task number", () => {
  const task = entry("a", "任务条-样式1", "新客", "", { taskIndex: 2, stateTitle: "点击后" });
  const [item] = rename([task]);
  assert.equal(item.fileName, "2_新客.png");
  assert.equal(item.filePath, "【落地页】/任务/已完成/2_新客.png");
});

test("signup state is not relabelled as already signed up", () => {
  const item = entry("a", "核心玩法模块-抽奖消返-3列", "新客", "", { stateTitle: "报名状态" });
  assert.equal(rename([item])[0].filePath, "【落地页】/抽奖消耗返/报名状态/新客.png");
});

test("special slices keep role, card name and prize index", () => {
  const items = rename([
    { ...entry("a", "用户教育案例-样式1"), exportKind: "case-showcase-shell" },
    { ...entry("b", "用户教育案例-样式1", "人群1", "", { sliceTitle: "旅行" }), exportKind: "case-showcase-card" },
    { ...entry("c", "节点指南", "新客", "", { sliceTitle: "服装配饰行业" }), exportKind: "node-guide-card" },
    { ...entry("d", "弹窗-中奖", "", "", { prizeIndex: 2, prizeName: "10元流量券", audienceScopeId: "popup" }), exportKind: "lottery-popup" },
    { ...entry("e", "弹窗-未中奖", "", "", { stateTitle: "未中奖", audienceScopeId: "popup" }), exportKind: "lottery-popup" },
  ]);
  assert.deepEqual(items.map((item) => item.fileName), [
    "底板.png", "旅行.png", "新客_服装配饰.png",
    "奖品2-10元流量券.png", "默认.png",
  ]);
  assert.equal(items[3].filePath, "【弹窗】/抽奖结果/中奖/奖品2-10元流量券.png");
  assert.equal(items[4].filePath, "【弹窗】/抽奖结果/未中奖/默认.png");
});

test("fallback pages use actual page purposes and resource positions have short names", () => {
  const fallback = { ...entry("a", "无活动提示"), pageId: "hot" };
  const [hot] = rename([fallback], { pages: [{ id: "hot", name: "活动火爆", isSystemFallback: true }] });
  assert.equal(hot.filePath, "【兜底页】活动火爆/活动火爆/默认.png");
  const [resource] = rename([entry("b", "下单页弹窗", "入驻机构")], { workflowType: "resource" });
  assert.equal(resource.filePath, "【资源位】/下单弹窗/入驻机构.png");
});

test("page backgrounds omit internal background labels", () => {
  const [background] = rename([{
    ...entry("bg", "头图", "背景+头图", "页面背景"), exportKind: "page-background",
  }]);
  assert.equal(background.filePath, "【落地页】/页面底图/默认.png");
  assert.equal(background.exportModuleName, "页面底图");
});

test("named dimensions take precedence over autogenerated copy versions", () => {
  const [item] = rename([entry("a", "头图", "文案版本 2", "入驻机构")]);
  assert.equal(item.fileName, "入驻机构.png");
});

test("each module groups every audience and state in a single folder", () => {
  const items = rename([
    entry("a", "核心权益模块-bigday发券-样式1", "新客", "", { stateTitle: "报名前" }),
    entry("b", "核心权益模块-bigday发券-样式1", "老客", "", { stateTitle: "已报名" }),
    entry("c", "头图", "新客"),
  ]);
  assert.deepEqual(items.map((item) => item.filePath), [
    "【落地页】/发券/未报名/新客.png",
    "【落地页】/发券/已报名/老客.png",
    "【落地页】/头图/新客.png",
  ]);
});

test("task titles and child task states stay in their parent module folder", () => {
  const items = rename([
    { ...entry("title", "任务列表", "新客", "", { audienceScopeId: "tasks" }), exportKind: "task-list-title" },
    entry("task", "任务条-样式1", "新客", "", { audienceScopeId: "tasks", taskIndex: 1, stateTitle: "点击前" }),
  ]);
  assert.deepEqual(items.map((item) => item.filePath), [
    "【落地页】/任务/标题_新客.png",
    "【落地页】/任务/未完成/1_新客.png",
  ]);
});

test("distinct instances of the same module receive distinct folders", () => {
  const items = rename([
    { ...entry("first", "头图"), nodeId: "header1" },
    { ...entry("second", "头图"), nodeId: "header2" },
  ]);
  assert.deepEqual(items.map((item) => item.filePath), [
    "【落地页】/头图/默认.png", "【落地页】/头图_2/默认.png",
  ]);
});

test("deduplication never overwrites real numbered names and keeps existing IDs", () => {
  const items = rename([entry("a", "头图", "新客"), entry("b", "头图", "新客"), entry("c", "头图", "新客_2")]);
  assert.equal(new Set(items.map((item) => item.filePath)).size, 3);
  assert.deepEqual(items.map((item) => item.id), ["a", "b", "c"]);
  assert.equal(items[2].fileName, "新客_2.png");
});

test("renaming does not mutate persisted pages, props or source entries", () => {
  const items = [entry("a", "头图", "个人素人")];
  const original = structuredClone({ pages, items });
  rename(items);
  assert.deepEqual({ pages, items }, original);
});

test("archive names use the same concise module and activity names", () => {
  assert.equal(makeExportArchiveName("双11活动"), "双11活动_切图.zip");
  assert.equal(makeExportArchiveName("抽奖消耗返"), "抽奖消耗返_切图.zip");
});
